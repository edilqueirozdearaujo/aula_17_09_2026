package aula_17_09_2026;

public class Aviao {
	String fabricante;
	String modelo;
	double velocidade;
	int    passageiros;
	
	public void setFabricante(String f) {
		this.fabricante = f;
	}
	public void setModelo(String m) {
		this.modelo = m;
	}
	public void setVelocidade(double v) {
		this.velocidade = v;
	}
	public void setPassageiros(int p) {
		this.passageiros = p;
	}
	
	public String getFabricante() {
		return fabricante;
	}
	public String getModelo() {
		return modelo;
	}
	public double getVelocidade() {
		return velocidade;
	}
	public int getPassageiros() {
		return passageiros;
	}

	
	
	
}
